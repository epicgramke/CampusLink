-- Campus Connect Kenya — Supabase database setup
-- Run in Supabase Dashboard > SQL Editor > New query.
-- This script creates profiles and listings with row-level security.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text not null default '',
  campus text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('marketplace','food','hostels','jobs','internships','lost-found')),
  title text not null check (char_length(title) between 1 and 90),
  description text not null check (char_length(description) between 1 and 1200),
  price numeric(12,2) check (price is null or price >= 0),
  location text not null default '',
  contact_email text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.listings enable row level security;

drop policy if exists "Profiles are readable by owner" on public.profiles;
create policy "Profiles are readable by owner" on public.profiles
for select to authenticated using (auth.uid() = id);

drop policy if exists "Users can insert their profile" on public.profiles;
create policy "Users can insert their profile" on public.profiles
for insert to authenticated with check (auth.uid() = id);

drop policy if exists "Users can update their profile" on public.profiles;
create policy "Users can update their profile" on public.profiles
for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Authenticated users can read active listings" on public.listings;
create policy "Authenticated users can read active listings" on public.listings
for select to authenticated using (is_active = true or auth.uid() = user_id);

drop policy if exists "Users can create their own listings" on public.listings;
create policy "Users can create their own listings" on public.listings
for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "Users can update their own listings" on public.listings;
create policy "Users can update their own listings" on public.listings
for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own listings" on public.listings;
create policy "Users can delete their own listings" on public.listings
for delete to authenticated using (auth.uid() = user_id);

create index if not exists listings_category_created_at_idx
on public.listings (category, created_at desc);

-- Optional: automatically create a profile record after signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, display_name, campus)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'display_name', ''),
    coalesce(new.raw_user_meta_data ->> 'campus', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();
